#!/usr/bin/env node
/**
 * Generates frontend/src/lib/abi.ts from the committed ABIs in abi/.
 *
 * The ABI files are the source of truth. abi/BountyVault.json is exported from
 * the Arc Studio workspace after a deploy:
 *
 *   npx arc-studio cat contracts/out/BountyVault.sol/BountyVault.json \
 *     --session clearaudit | node -e "
 *       let s='';process.stdin.on('data',d=>s+=d).on('end',()=>{
 *         const a=JSON.parse(s).abi;
 *         require('fs').writeFileSync('abi/BountyVault.json',
 *           JSON.stringify({contract:'BountyVault',abi:a},null,2));
 *       })"
 *
 * Never hand-edit frontend/src/lib/abi.ts.
 *
 *   node scripts/gen-abi.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "frontend/src/lib/abi.ts");

function load(file) {
  const { abi, contract } = JSON.parse(readFileSync(resolve(root, "abi", file), "utf8"));
  if (!Array.isArray(abi) || abi.length === 0) {
    throw new Error(`abi/${file} has no abi array`);
  }
  const names = new Set(abi.map((entry) => entry.name).filter(Boolean));
  return { abi, contract, names };
}

const vault = load("BountyVault.json");
const erc20 = load("ERC20.json");

for (const required of ["createBounty", "releaseBounty", "disputeBounty", "getDeal", "nextDealId"]) {
  if (!vault.names.has(required)) throw new Error(`BountyVault ABI is missing ${required}()`);
}
for (const required of ["balanceOf", "allowance", "approve", "decimals"]) {
  if (!erc20.names.has(required)) throw new Error(`ERC20 ABI is missing ${required}()`);
}

const out = [
  "// AUTO-GENERATED by scripts/gen-abi.mjs — do not edit by hand.",
  "// Source: abi/BountyVault.json (exported from the Arc Studio workspace) and abi/ERC20.json.",
  "",
  `export const BOUNTY_VAULT_ABI = ${JSON.stringify(vault.abi, null, 2)} as const;`,
  "",
  `export const ERC20_ABI = ${JSON.stringify(erc20.abi, null, 2)} as const;`,
  "",
  "export const DEAL_STATUS = {",
  "  None: 0,",
  "  Open: 1,",
  "  Disputed: 2,",
  "  Released: 3,",
  "  ResolvedToResearcher: 4,",
  "  ResolvedToCompany: 5,",
  "} as const;",
  "",
  "export type DealStatus = (typeof DEAL_STATUS)[keyof typeof DEAL_STATUS];",
  "",
  "export const DEAL_STATUS_LABEL: Record<number, string> = {",
  '  0: "None",',
  '  1: "Open",',
  '  2: "Disputed",',
  '  3: "Released",',
  '  4: "Resolved to researcher",',
  '  5: "Resolved to company",',
  "};",
  "",
];

writeFileSync(target, out.join("\n"));
console.log(`wrote ${target} (${vault.abi.length} vault entries, ${erc20.abi.length} erc20 entries)`);
